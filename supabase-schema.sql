-- Run this SQL in Supabase SQL Editor.
create table if not exists public.rsvps (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  attendance text not null check (attendance in ('yes','no','maybe')),
  guests integer not null default 1 check (guests between 1 and 20),
  message text,
  created_at timestamptz not null default now()
);
-- The website writes/reads through the server using the service-role key.
-- Do not expose SUPABASE_SERVICE_ROLE_KEY in any NEXT_PUBLIC variable.
alter table public.rsvps enable row level security;
